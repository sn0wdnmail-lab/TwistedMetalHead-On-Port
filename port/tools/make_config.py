#!/usr/bin/env python3
"""Build the PS2Recomp inputs for Head-On from tmdis's function map and the analyzer's SDK matches.

usage: make_config.py <tmho_functions.csv> <analyzer.toml> <out_dir> <elf> <output_dir> [stub_rules.txt]

stub_rules.txt: one rule per line. "-Name" keeps the game's own code for an SDK function the
analyzer would bind to a runtime handler; "handler@0xADDRESS" adds a binding.

Writes <out_dir>/tmho_functions_named.csv (tmdis boundaries, SDK names where the analyzer
identified the function) and <out_dir>/tmho.toml (handler@address bindings for every SDK
function the runtime implements). The analyzer reads the SCE symbol database embedded in
ps2_analyzer; tmdis supplies the boundaries for everything else.
"""
import re
import sys
from pathlib import Path


def readList(text, key):
    m = re.search(r'^' + key + r' = \[(.*?)^\]', text, re.S | re.M)
    if not m:
        return []
    out = []
    for name, addr in re.findall(r'"([^"@]+)@0x([0-9A-Fa-f]+)"', m.group(1)):
        out.append((name, int(addr, 16)))
    return out


def main():
    csvPath, analyzerPath, outDir, elf, outputDir = sys.argv[1:6]
    rules = []
    if len(sys.argv) > 6:
        for line in Path(sys.argv[6]).read_text().splitlines():
            line = line.split('#', 1)[0].strip()
            if line:
                rules.append(line)
    excluded = {r[1:] for r in rules if r.startswith('-')}
    extra = [r for r in rules if not r.startswith('-')]
    text = Path(analyzerPath).read_text()
    stubs = readList(text, 'stubs')
    entries = readList(text, 'entry_points')

    rows = []
    starts = {}
    for line in Path(csvPath).read_text().splitlines()[1:]:
        name, start, end, size = line.split(',')
        rows.append([name, int(start, 16), int(end, 16), int(size)])
        starts[int(start, 16)] = len(rows) - 1

    # tmdis only starts a function where something calls or references it. An SDK function
    # reached only through a table (or not at all) is merged into the function before it:
    # split that function at the start the symbol database gives.
    split = []
    for name, addr in stubs + entries:
        if addr in starts:
            continue
        for row in rows:
            if row[1] < addr < row[2]:
                rows.append([name, addr, row[2], row[2] - addr])
                row[2] = addr
                row[3] = addr - row[1]
                split.append((name, addr))
                break
    rows.sort(key=lambda r: r[1])
    starts = {row[1]: i for i, row in enumerate(rows)}

    used = {}
    missing = []
    for name, addr in stubs + entries:
        if addr not in starts:
            missing.append((name, addr))
            continue
        unique = name
        if name in excluded:
            # ps2_recomp binds any function named like a runtime handler, so an excluded SDK
            # function keeps its name with a suffix the runtime does not know.
            unique = name + '_game'
        if unique in used and used[unique] != addr:
            unique = '%s_%08X' % (unique, addr)
        used[unique] = addr
        rows[starts[addr]][0] = unique

    out = Path(outDir)
    out.mkdir(parents=True, exist_ok=True)
    with open(out / 'tmho_functions_named.csv', 'w', newline='\n') as f:
        f.write('Name,Start,End,Size\n')
        for name, start, end, size in rows:
            f.write('%s,0x%08X,0x%08X,%d\n' % (name, start, end, size))

    bindings = ['%s@0x%08X' % (name, addr) for name, addr in stubs
                if addr in starts and name not in excluded]
    bindings += extra
    q = lambda s: "'" + s + "'"
    with open(out / 'tmho.toml', 'w', newline='\n') as f:
        f.write('# PS2Recomp config for Twisted Metal: Head-On - Extra Twisted Edition (SCUS-97621, NTSC-U).\n')
        f.write('# Generated by tools/make_config.py: function boundaries from tmdis, SDK functions\n')
        f.write('# identified by ps2_analyzer\'s SCE symbol database and bound to runtime handlers.\n\n')
        f.write('[general]\n')
        f.write('input = %s\n' % q(elf))
        f.write('output = %s\n' % q(outputDir))
        f.write('ghidra_output = %s\n' % q(str(Path(outDir) / 'tmho_functions_named.csv')))
        f.write('single_file_output = false\npatch_syscalls = false\npatch_cop0 = true\npatch_cache = true\n')
        f.write('stubs = [\n')
        for b in bindings:
            f.write('  "%s",\n' % b)
        f.write(']\nskip = [\n]\n')

    print('%d functions (%d split at SDK starts), %d named, %d runtime bindings'
          % (len(rows), len(split), len(used), len(bindings)))
    for name, addr in missing:
        print('outside every function: %s at 0x%08X' % (name, addr))


if __name__ == '__main__':
    main()
